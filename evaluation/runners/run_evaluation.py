"""
Automated Evaluation Runner for SIH PS 26117 Industrial Document Intelligence.
Runs the 25-question industrial evaluation suite and exports the evaluation report.
"""

from pathlib import Path
import json

from evaluation.engine.evaluator import RAGEvaluator


def generate_markdown_report(eval_output: dict, output_path: Path):
    """Formats and writes a comprehensive Markdown evaluation report."""
    summary = eval_output["summary"]
    detailed = eval_output["detailed_results"]
    breakdown = summary["category_breakdown"]
    failures = summary["failure_cases"]

    lines = [
        "# Industrial Document Intelligence Evaluation Report",
        "",
        "**Project:** SIH PS 26117 — Sovereign Industrial AI Workbench  ",
        "**Evaluation Target:** Pump P-101 Industrial RAG & Multimodal Pipeline  ",
        "**Evaluator:** Sowmya (Evaluation & Data Analytics Engineer)  ",
        "",
        "---",
        "",
        "## 1. Executive Summary & Benchmark Metrics",
        "",
        "```text",
        f"Total questions: {summary['total_questions']}",
        f"Retrieved relevant source: {summary['retrieved_relevant_source']}",
        f"Correct source: {summary['correct_source']}",
        f"Answer acceptable: {summary['answer_acceptable']}",
        f"Multimodal questions: {summary['multimodal_questions']}",
        f"Multimodal successful: {summary['multimodal_successful']}",
        "```",
        "",
        "### Key Quantitative Indicators",
        "",
        f"* **Retrieval Success Rate:** `{summary['retrieval_success_rate'] * 100:.1f}%` ({summary['retrieved_relevant_source']}/{summary['total_questions']})",
        f"* **Source Attribution Correctness:** `{summary['source_correctness_rate'] * 100:.1f}%` ({summary['correct_source']}/{summary['total_questions']})",
        f"* **Factual Answer Acceptability:** `{summary['answer_acceptable_rate'] * 100:.1f}%` ({summary['answer_acceptable']}/{summary['total_questions']})",
        f"* **Multimodal Success Rate:** `{(summary['multimodal_successful'] / max(1, summary['multimodal_questions'])) * 100:.1f}%` ({summary['multimodal_successful']}/{summary['multimodal_questions']})",
        "",
        "---",
        "",
        "## 2. Category-Wise Performance Breakdown",
        "",
        "| Category | Questions | Relevant Retrieved | Correct Source | Answer Acceptable |",
        "| :--- | :---: | :---: | :---: | :---: |",
    ]

    for cat, stats in breakdown.items():
        lines.append(
            f"| **{cat}** | {stats['total']} | {stats['retrieval_success']}/{stats['total']} | "
            f"{stats['source_correctness']}/{stats['total']} | {stats['answer_acceptable']}/{stats['total']} |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 3. Failure Mode Taxonomy & Weakness Analysis",
        "",
    ])

    if not failures:
        lines.append("*No critical failure cases detected across all 25 benchmark items.*")
    else:
        lines.append(f"Detected **{len(failures)}** query instances with partial retrieval or fact omissions:")
        lines.append("")
        for f in failures:
            lines.extend([
                f"### [{f['id']}] {f['category']} — Failure: `{f['failure_type']}`",
                f"* **Question:** {f['question']}",
                f"* **Missing Sources:** `{f['missing_sources'] if f['missing_sources'] else 'None'}`",
                f"* **Missing Key Facts:** `{f['missing_facts'] if f['missing_facts'] else 'None'}`",
                "",
            ])

    lines.extend([
        "---",
        "",
        "## 4. Engineering Recommendations for RAG Optimization",
        "",
        "1. **Cross-Document Query Routing:** For synthesis questions spanning SOP, Incident, and Manual (e.g., cross-referencing past bearing replacements with SOP escalation limits), implement multi-query routing to prevent single-document bias.",
        "2. **Table-Aware Extraction:** Ensure numerical tabular parameters (such as vibration thresholds `4.5–7.1 mm/s RMS` and operating pressure `4.0–4.5 bar`) are indexed with header context so chunk boundaries do not sever parameter names from units.",
        "3. **Telemetry-to-SOP Linking:** Multimodal queries benefit directly from pre-binding Data Analytics anomaly tags (`CRITICAL`, `WARNING`) with the corresponding SOP section (`Section 9 Critical Vibration Response`).",
        "",
        "---",
        "*Report automatically generated by `evaluation/runners/run_evaluation.py`.*",
    ])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    print("=" * 70)
    print("SIH PS 26117 - INDUSTRIAL RAG & DOCUMENT EVALUATION RUNNER")
    print("=" * 70)

    evaluator = RAGEvaluator()
    print(f"Loaded test set with {len(evaluator.test_set.get('questions', []))} questions.")
    print("Executing evaluation benchmarks across local document corpus...")

    results = evaluator.run_all(top_k=4)
    summary = results["summary"]

    print("\n--- EVALUATION BENCHMARK RESULTS ---")
    print(f"Total questions: {summary['total_questions']}")
    print(f"Retrieved relevant source: {summary['retrieved_relevant_source']}")
    print(f"Correct source: {summary['correct_source']}")
    print(f"Answer acceptable: {summary['answer_acceptable']}")
    print(f"Multimodal questions: {summary['multimodal_questions']}")
    print(f"Multimodal successful: {summary['multimodal_successful']}")

    print("\nCategory Breakdown:")
    for cat, stats in summary["category_breakdown"].items():
        print(f"  - {cat:28s}: {stats['answer_acceptable']}/{stats['total']} acceptable ({stats['source_correctness']}/{stats['total']} correct sources)")

    # Export report
    workspace_root = Path(__file__).resolve().parent.parent.parent
    report_path = workspace_root / "evaluation" / "reports" / "evaluation_report.md"
    generate_markdown_report(results, report_path)
    print(f"\nSaved detailed evaluation report -> {report_path}")
    print("=" * 70)


if __name__ == "__main__":
    main()
